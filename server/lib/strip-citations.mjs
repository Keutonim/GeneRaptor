/**
 * Убирает inline-маркеры источников {{src:...}} из markdown.
 *
 * Perplexity-стиль источниковедения (ADDENDUM от 2026-07-10): article-author
 * помечает каждый фактический
 * тезис маркером {{src:N}}, factchecker проверяет валидность маркеров,
 * а перед публикацией (до humanizer) маркеры снимаются — финальный текст
 * не содержит ссылок на источники. Реестр sourceMapRu остаётся только в
 * AgentRun.outputJson для аудит-следа.
 *
 * Маркер имеет вид {{src:N}} или {{src:card}}, где N — номер источника в
 * реестре автора. Регулярка ловит любую форму {{src:...}}.
 */

const CITATION_PATTERN = /\s*\{\{src:[^}]+\}\}/g;

/**
 * Убирает inline-маркеры источников {{src:...}} из markdown.
 * Используется перед публикацией: финальный текст не содержит ссылок на источники.
 *
 * Заодно убирает предшествующий маркеру пробел (\s* перед паттерном), чтобы
 * не оставалось двойных/висячих пробелов на месте вырезанного маркера.
 *
 * @param {string} markdown
 * @returns {string}
 */
export function stripCitations(markdown) {
  if (!markdown || typeof markdown !== 'string') return markdown;
  // Убираем маркер + предшествующий пробел (чтобы не осталось двойных пробелов)
  return markdown.replace(CITATION_PATTERN, '');
}
